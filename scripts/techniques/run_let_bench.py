"""`let` against inlining in the kernel, on synthetic files that import nothing (core Lean only).

Each file is one `decide +kernel` check of a `Nat.rec` loop of `s` steps (`i` the recursor's index,
`r` the accumulator), whose step binds a value `x` computed from `i` and uses it. The variants are how
`x` is bound:

| variant  | step                                                  |
|----------|-------------------------------------------------------|
| `inline` | the value written at each use: ours                   |
| `let`    | `let x := v; body` (`Expr.letE`)                      |
| `have`   | `have x := v; body` (a non-dependent `let`)           |
| `beta`   | `(fun x => body) v`                                   |

Two experiments:

* `once`: `x = i &&& 3`, used once: `r + x`.
* `shared`: `x = (i · i) % 1000003`, used four times: `r + x + x · x + x`. Inlined, the value is
  written four times; bound, once.

The loop with the step `r + 3` (`base`, 30.8 k instructions a step) is subtracted. Every operation is a
`Nat` primitive with `nat_lit` constants, so only the binding differs.

Usage: python3 scripts/techniques/run_let_bench.py run [OUT.jsonl]
       sage -python scripts/techniques/run_let_bench.py plot [OUT.jsonl]     (CSV and plot next to OUT)
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from technique_bench import (append, done, load, measure, out_and_args, style,  # noqa: E402
                             write_csv)

SS = [1000, 4000, 16000, 64000, 256000]
P = 1000003

VALUES = {"once": "Nat.land i (nat_lit 3)",
          "shared": f"Nat.mod (Nat.mul i i) (nat_lit {P})"}


def body(exp: str, x: str) -> str:
    if exp == "once":
        return f"Nat.add r {x}"
    return f"Nat.add (Nat.add (Nat.add r {x}) (Nat.mul {x} {x})) {x}"


def step(exp: str, variant: str) -> str:
    v = f"({VALUES[exp]})"
    if variant == "inline":
        return body(exp, v)
    if variant == "let":
        return f"let x := {v}\n    {body(exp, 'x')}"
    if variant == "have":
        return f"have x := {v}\n    {body(exp, 'x')}"
    if variant == "beta":
        return f"(fun x => {body(exp, 'x')}) {v}"
    raise ValueError(variant)


EXPS = {"once": ["inline", "let", "have", "beta"], "shared": ["inline", "let", "have", "beta"]}


def expected(s: int, exp: str) -> int:
    if exp == "base":
        return 3 * s
    r = 0
    for i in range(s):
        if exp == "once":
            r += i & 3
        else:
            x = i * i % P
            r = r + x + x * x + x
    return r


def source(s: int, exp: str, variant: str) -> str:
    st = "Nat.add r (nat_lit 3)" if exp == "base" else step(exp, variant)
    return f"""/-! `let` benchmark, `{exp}`, variant `{variant}`, {s} steps. Generated by
`scripts/techniques/run_let_bench.py`. -/
set_option linter.unusedVariables false

noncomputable def loop (n : Nat) : Nat :=
  @Nat.rec (fun _ => Nat) (nat_lit 0) (fun i r =>
    {st}) n

theorem check : Nat.beq (loop (nat_lit {s})) (nat_lit {expected(s, exp)}) = true := by
  decide +kernel
"""


def run(out: Path) -> None:
    have = done(out, "exp", "variant", "s")
    jobs = [("base", "base")] + [(e, v) for e, vs in EXPS.items() for v in vs]
    for s in SS:
        for exp, v in jobs:
            if (exp, v, s) in have:
                continue
            row = {"exp": exp, "variant": v, "s": s}
            try:
                row |= measure(source(s, exp, v))
            except RuntimeError as e:
                msg = str(e)
                row["error"] = (msg.splitlines()[0] if msg.startswith("kernel:") else
                                next((ln for ln in msg.splitlines() if "error" in ln), msg))[:300]
            append(out, row)


def net(rows: list[dict]) -> list[dict]:
    """Each variant's kernel cost minus the loop `r + 3`, per step."""
    base = {r["s"]: r for r in rows if r["exp"] == "base" and "error" not in r}
    return [r | {"net_kernel_G": round(r["kernel_G"] - base[r["s"]]["kernel_G"], 4),
                 "k_instr_per_step": round((r["kernel_G"] - base[r["s"]]["kernel_G"]) * 1e6
                                           / r["s"], 2)}
            for r in rows if r["exp"] != "base" and "error" not in r and r["s"] in base]


COLORS = {"inline": "#2a78d6", "let": "#e34948", "have": "#eda100", "beta": "#1baf7a"}
MARKERS = {"inline": "D", "let": "o", "have": "s", "beta": "^"}
LABELS = {"inline": "inlined (ours)", "let": "let x := v", "have": "have x := v",
          "beta": "(fun x => …) v"}


def plot(out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = load(out)
    nets = net(rows)
    write_csv(rows, out.parent / "results.csv")
    fig, axs = plt.subplots(1, 2, figsize=(12, 4.8), dpi=150)
    titles = {"once": "x = i &&& 3, used once: per step",
              "shared": "x = i² mod 1000003, used four times: per step"}
    for ax, exp in zip(axs, EXPS):
        for v in EXPS[exp]:
            pts = sorted((r["s"], r["k_instr_per_step"]) for r in nets
                         if r["exp"] == exp and r["variant"] == v)
            if pts:
                ax.plot(*zip(*pts), color=COLORS[v], marker=MARKERS[v], markersize=6, linewidth=2,
                        label=LABELS[v])
        style(ax, titles[exp], "loop steps s", "thousand instructions, net of the loop")
        ax.set_yscale("linear")
        ax.set_ylim(bottom=0)
        ax.legend(frameon=False, fontsize=8)
    fig.suptitle("let against inlining in the kernel", x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(out.parent / "let.png")


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("run", "plot"):
        raise SystemExit(__doc__)
    out, _ = out_and_args("let", sys.argv[2:])
    if sys.argv[1] == "run":
        run(out)
    else:
        plot(out)


if __name__ == "__main__":
    main()

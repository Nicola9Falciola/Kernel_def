"""Branches in the kernel: `if` against a raw `Bool.rec`, on synthetic files that import nothing.

Each file is one `decide +kernel` check of a `Nat.rec` loop of `s` steps. Step `i` (`i` the
recursor's index, a literal) adds 3 to the accumulator when `x = i &&& 3` is at most 1, and 5
otherwise, so both branches are taken, alternately in pairs. The loop's result is checked against the
value computed here. Two experiments:

* `branch`: how the test and the branch are written.

  | variant      | step                                                                   |
  |--------------|------------------------------------------------------------------------|
  | `nobranch`   | `r + 3`: the loop without a branch (subtracted)                        |
  | `ite_prop`   | `if x ≤ 1 then r + 3 else r + 5` (`ite`, `Nat.decLe`)                  |
  | `ite_bool`   | `if Nat.ble x 1 = true then … else …` (`ite`, `instDecidableEqBool`)   |
  | `cond`       | `bif Nat.ble x 1 then … else …` (`cond`)                               |
  | `match`      | `match Nat.ble x 1 with \\| true => … \\| false => …` (a matcher)        |
  | `bool_rec`   | `Bool.rec (r + 5) (r + 3) (Nat.ble x 1)`: ours                         |

  The additions are `Nat.add` with `nat_lit`s in every variant, so only the branch differs.

* `and`: a conjunction, the step adding 3 when `1 ≤ x ∧ x ≤ 2` (`x = i &&& 3`):
  `and_ite` (`if 1 ≤ x ∧ x ≤ 2`, `instDecidableAnd`), `and_op` (`Bool.rec … (Nat.ble 1 x && Nat.ble x 2)`)
  and `and_rec` (ours: nested `Bool.rec`, the second test only when the first holds).

Usage: python3 scripts/techniques/run_branch_bench.py run [OUT.jsonl]
       sage -python scripts/techniques/run_branch_bench.py plot [OUT.jsonl]     (CSV and plot next to OUT)
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from technique_bench import (append, done, load, measure, out_and_args, style,  # noqa: E402
                             write_csv)

SS = [1000, 4000, 16000, 64000, 256000]

A3, A5 = "Nat.add r (nat_lit 3)", "Nat.add r (nat_lit 5)"
X = "(Nat.land i (nat_lit 3))"
BRANCH = {
    "nobranch": A3,
    "ite_prop": f"if {X} ≤ 1 then {A3} else {A5}",
    "ite_bool": f"if Nat.ble {X} (nat_lit 1) = true then {A3} else {A5}",
    "cond": f"bif Nat.ble {X} (nat_lit 1) then {A3} else {A5}",
    "match": f"match Nat.ble {X} (nat_lit 1) with\n    | true => {A3}\n    | false => {A5}",
    "bool_rec": f"@Bool.rec (fun _ => Nat) ({A5}) ({A3}) (Nat.ble {X} (nat_lit 1))",
}
AND = {
    "and_ite": f"if 1 ≤ {X} ∧ {X} ≤ 2 then {A3} else {A5}",
    "and_op": f"@Bool.rec (fun _ => Nat) ({A5}) ({A3}) "
              f"(Nat.ble (nat_lit 1) {X} && Nat.ble {X} (nat_lit 2))",
    "and_rec": f"@Bool.rec (fun _ => Nat) ({A5})\n      (@Bool.rec (fun _ => Nat) ({A5}) ({A3}) "
               f"(Nat.ble {X} (nat_lit 2)))\n      (Nat.ble (nat_lit 1) {X})",
}
EXPS = {"branch": BRANCH, "and": AND}


def expected(s: int, exp: str, variant: str) -> int:
    if variant == "nobranch":
        return 3 * s
    test = (lambda x: x <= 1) if exp == "branch" else (lambda x: 1 <= x <= 2)
    return sum(3 if test(i & 3) else 5 for i in range(s))


def source(s: int, exp: str, variant: str) -> str:
    return f"""/-! Branch benchmark, `{exp}`, variant `{variant}`, {s} steps. Generated by
`scripts/techniques/run_branch_bench.py`. -/
set_option linter.unusedVariables false

noncomputable def loop (n : Nat) : Nat :=
  @Nat.rec (fun _ => Nat) (nat_lit 0) (fun i r =>
    {EXPS[exp][variant]}) n

theorem check : Nat.beq (loop (nat_lit {s})) (nat_lit {expected(s, exp, variant)}) = true := by
  decide +kernel
"""


def run(out: Path) -> None:
    have = done(out, "exp", "variant", "s")
    for s in SS:
        for exp, vs in EXPS.items():
            for v in vs:
                if (exp, v, s) in have:
                    continue
                row = {"exp": exp, "variant": v, "s": s}
                try:
                    row |= measure(source(s, exp, v))
                except RuntimeError as e:
                    msg = str(e)
                    row["error"] = (msg.splitlines()[0] if msg.startswith("kernel:") else
                                    next((ln for ln in msg.splitlines() if "error" in ln),
                                         msg))[:300]
                append(out, row)


def net(rows: list[dict]) -> list[dict]:
    """Each variant's kernel cost minus the loop without a branch, per step."""
    base = {r["s"]: r for r in rows if r["variant"] == "nobranch" and "error" not in r}
    return [r | {"net_kernel_G": round(r["kernel_G"] - base[r["s"]]["kernel_G"], 4),
                 "k_instr_per_step": round((r["kernel_G"] - base[r["s"]]["kernel_G"]) * 1e6
                                           / r["s"], 2)}
            for r in rows if r["variant"] != "nobranch" and "error" not in r and r["s"] in base]


COLORS = {"ite_prop": "#e34948", "ite_bool": "#eb6834", "cond": "#eda100", "match": "#1baf7a",
          "bool_rec": "#2a78d6", "and_ite": "#e34948", "and_op": "#eda100", "and_rec": "#2a78d6"}
MARKERS = {"ite_prop": "o", "ite_bool": "s", "cond": "^", "match": "v", "bool_rec": "D",
           "and_ite": "o", "and_op": "^", "and_rec": "D"}
LABELS = {"ite_prop": "if x ≤ 1 (Nat.decLe)", "ite_bool": "if Nat.ble x 1 = true",
          "cond": "bif Nat.ble x 1", "match": "match Nat.ble x 1", "bool_rec": "Bool.rec (ours)",
          "and_ite": "if 1 ≤ x ∧ x ≤ 2", "and_op": "Bool.rec on (… && …)",
          "and_rec": "nested Bool.rec (ours)"}


def plot(out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = load(out)
    nets = net(rows)
    write_csv(rows, out.parent / "results.csv")
    fig, axs = plt.subplots(1, 3, figsize=(16, 4.8), dpi=150)
    panels = [("branch", "net_kernel_G", "One branch: kernel, net of the loop", "billions"),
              ("branch", "k_instr_per_step", "One branch: per step", "thousand instructions"),
              ("and", "k_instr_per_step", "A conjunction: per step", "thousand instructions")]
    for ax, (exp, key, title, ylabel) in zip(axs, panels):
        for v in EXPS[exp]:
            pts = sorted((r["s"], r[key]) for r in nets
                         if r["exp"] == exp and r["variant"] == v and r[key] > 0)
            if pts:
                ax.plot(*zip(*pts), color=COLORS[v], marker=MARKERS[v], markersize=6, linewidth=2,
                        label=LABELS[v])
        style(ax, title, "loop steps s", ylabel)
        if key == "k_instr_per_step":
            ax.set_yscale("linear")
            ax.set_ylim(bottom=0)
        ax.legend(frameon=False, fontsize=8)
    fig.suptitle("Branches in the kernel: if against Bool.rec", x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(out.parent / "branch.png")


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("run", "plot"):
        raise SystemExit(__doc__)
    out, _ = out_and_args("branch", sys.argv[2:])
    if sys.argv[1] == "run":
        run(out)
    else:
        plot(out)


if __name__ == "__main__":
    main()

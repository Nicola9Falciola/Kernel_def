"""`nat_lit` against `OfNat` numerals, on synthetic files that import nothing (core Lean only).

A numeral `123 : ℕ` elaborates to `@OfNat.ofNat ℕ 123 (instOfNatNat 123)`: an instance is synthesized
for it, and the kernel unfolds `instOfNatNat` to reach the literal. `nat_lit 123` is the raw literal
(`Expr.lit (.natVal 123)`). Two experiments:

* `data`: `m` random 576-bit literals in one `List ℕ`, and one `decide +kernel` check that their sum
  (a bare `List.rec` of `Nat.add`) is the total computed here. Four variants, the 2 × 2 of how the
  literals are written (`ofnat`, `natlit`) and how the list is defined (`def`, compiled;
  `noncomputable def`, not compiled): `ofnat_def`, `ofnat_nc`, `natlit_def`, `natlit_nc`.
* `loop`: a `Nat.rec` loop of `s` steps whose step adds the constant 3, written `3` (`ofnat`) or
  `nat_lit 3` (`natlit`).

Measured by `technique_bench.measure`: the kernel (full − no kernel) and the elaboration (no kernel −
an empty file), instructions, time and peak memory.

Usage: python3 scripts/techniques/run_natlit_bench.py run [OUT.jsonl]
       sage -python scripts/techniques/run_natlit_bench.py plot [OUT.jsonl]     (CSV and plot next to OUT)
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from technique_bench import (append, done, load, measure, out_and_args, style,  # noqa: E402
                             write_csv)

DATA_M = [256, 1024, 4096, 16384, 65536]
LOOP_S = [1000, 4000, 16000, 64000, 256000]
DATA_VARIANTS = ["ofnat_def", "ofnat_nc", "natlit_def", "natlit_nc"]
LOOP_VARIANTS = ["ofnat", "natlit"]


def data_source(m: int, variant: str) -> str:
    rng = random.Random(m)
    xs = [rng.getrandbits(575) | (1 << 575) for _ in range(m)]
    lit = "nat_lit {}" if variant.startswith("natlit") else "{}"
    kw = "def" if variant.endswith("_def") else "noncomputable def"
    body = ",\n  ".join(lit.format(x) for x in xs)
    return f"""/-! `nat_lit` benchmark, `data`, variant `{variant}`, {m} literals. Generated by
`scripts/techniques/run_natlit_bench.py`. -/
set_option maxRecDepth 100000

noncomputable def sumL (l : List Nat) : Nat :=
  @List.rec Nat (fun _ => Nat) (nat_lit 0) (fun x _ r => Nat.add x r) l

{kw} rows : List Nat := [
  {body}]

theorem check : Nat.beq (sumL rows) (nat_lit {sum(xs)}) = true := by
  decide +kernel
"""


def loop_source(s: int, variant: str) -> str:
    c = "(nat_lit 3)" if variant == "natlit" else "3"
    return f"""/-! `nat_lit` benchmark, `loop`, variant `{variant}`, {s} steps. Generated by
`scripts/techniques/run_natlit_bench.py`. -/

noncomputable def loop (n : Nat) : Nat :=
  @Nat.rec (fun _ => Nat) (nat_lit 0) (fun _ r => Nat.add r {c}) n

theorem check : Nat.beq (loop (nat_lit {s})) (nat_lit {3 * s}) = true := by
  decide +kernel
"""


def run(out: Path) -> None:
    have = done(out, "exp", "variant", "size")
    jobs = [("data", v, m, data_source) for m in DATA_M for v in DATA_VARIANTS]
    jobs += [("loop", v, s, loop_source) for s in LOOP_S for v in LOOP_VARIANTS]
    for exp, v, size, gen in jobs:
        if (exp, v, size) in have:
            continue
        row = {"exp": exp, "variant": v, "size": size}
        try:
            row |= measure(gen(size, v))
        except RuntimeError as e:
            row["error"] = next((ln for ln in str(e).splitlines() if "error" in ln), str(e))[:300]
        append(out, row)


COLORS = {"ofnat_def": "#eb6834", "ofnat_nc": "#eda100", "natlit_def": "#6250d6",
          "natlit_nc": "#2a78d6", "ofnat": "#eb6834", "natlit": "#2a78d6"}
MARKERS = {"ofnat_def": "o", "ofnat_nc": "s", "natlit_def": "^", "natlit_nc": "D", "ofnat": "o",
           "natlit": "D"}
LABELS = {"ofnat_def": "OfNat numerals, def", "ofnat_nc": "OfNat numerals, noncomputable def",
          "natlit_def": "nat_lit, def", "natlit_nc": "nat_lit, noncomputable def (ours)",
          "ofnat": "constant 3 (OfNat)", "natlit": "constant nat_lit 3 (ours)"}


def plot(out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = [r for r in load(out) if "error" not in r]
    write_csv(load(out), out.parent / "results.csv")
    fig, axs = plt.subplots(1, 4, figsize=(18, 4.8), dpi=150)
    panels = [("data", "elab_G", "Data: elaboration", "instructions (billions)", "literals m"),
              ("data", "kernel_G", "Data: kernel", "instructions (billions)", "literals m"),
              ("data", "peak_GB", "Data: peak memory", "GB", "literals m"),
              ("loop", "kernel_G", "Loop constant: kernel", "instructions (billions)",
               "loop steps s")]
    for ax, (exp, key, title, ylabel, xlabel) in zip(axs, panels):
        for v in (DATA_VARIANTS if exp == "data" else LOOP_VARIANTS):
            pts = sorted((r["size"], r[key]) for r in rows
                         if r["exp"] == exp and r["variant"] == v and r[key] > 0)
            if pts:
                ax.plot(*zip(*pts), color=COLORS[v], marker=MARKERS[v], markersize=6, linewidth=2,
                        label=LABELS[v])
        style(ax, title, xlabel, ylabel)
    axs[0].legend(frameon=False, fontsize=8)
    axs[3].legend(frameon=False, fontsize=8)
    fig.suptitle("nat_lit against OfNat numerals", x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(out.parent / "natlit.png")


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("run", "plot"):
        raise SystemExit(__doc__)
    out, _ = out_and_args("natlit", sys.argv[2:])
    if sys.argv[1] == "run":
        run(out)
    else:
        plot(out)


if __name__ == "__main__":
    main()

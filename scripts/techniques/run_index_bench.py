"""Walking a list against indexing into it, in the kernel, on synthetic files that import nothing.

Each file holds `m` values `v_i < 2^32` and one `decide +kernel` check of `∑ i · v_i` against the value
computed here. The variants differ in how `v_i` is reached:

| variant   | how                                                                          |
|-----------|------------------------------------------------------------------------------|
| `sum`     | control: one `List.rec` summing the `v_i` (no position, so another total)    |
| `walk`    | ours: one `List.rec` over the list, carrying the position `i`               |
| `nth_rec` | a `Nat.rec` loop over `i` reading `nthQ rows i`, an index in kernel form (a bare `List.rec`, `Bool.rec` on `Nat.beq`) |
| `getD`    | the same loop reading `rows.getD i 0` (core)                                 |
| `array`   | the same loop reading `arr.getD i 0`, `arr = rows.toArray` (core `Array`)    |
| `packed`  | the same loop reading slot `i` of one literal `T` of `m` slots of 32 bits: `(T >>> 32 i) &&& (2^32 − 1)`, as the certificates' packed tables (`tblGet`) |

An indexed read walks `i` cells of the list, so the loops over a list are quadratic in `m`; the packed
read is one shift of a number of `32 m` bits. Sizes run upward; a variant killed at one size
(`TIME_LIMIT_S`, default here 300 s) is not run at the larger ones.

Usage: python3 scripts/techniques/run_index_bench.py run [OUT.jsonl] [m ...] [variants=v,v]
       sage -python scripts/techniques/run_index_bench.py plot [OUT.jsonl]     (CSV and plot next to OUT)
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ.setdefault("TIME_LIMIT_S", "300")
sys.path.insert(0, str(Path(__file__).resolve().parent))
from technique_bench import (append, done, load, measure, out_and_args, style,  # noqa: E402
                             write_csv)

MS = [250, 1000, 4000, 16000, 64000]
VARIANTS = ["sum", "walk", "nth_rec", "getD", "array", "packed"]
W = 32


def values(m: int) -> list[int]:
    return [(i * 2654435761 + 12345) % 2**W for i in range(m)]


DEFS = """set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false

/-- `l[j]`, or 0 past the end: a bare `List.rec`, the position counted down by `Nat.beq`. -/
noncomputable def nthQ (l : List Nat) : Nat → Nat :=
  @List.rec Nat (fun _ => Nat → Nat) (fun _ => nat_lit 0)
    (fun x _ r j => @Bool.rec (fun _ => Nat) (r (Nat.sub j (nat_lit 1))) x (Nat.beq j (nat_lit 0))) l
"""

LOOP = {
    "nth_rec": "nthQ rows i",
    "getD": "rows.getD i 0",
    "array": "arr.getD i 0",
    "packed": f"Nat.land (Nat.shiftRight T (Nat.mul (nat_lit {W}) i)) (nat_lit {2**W - 1})",
}


def source(m: int, variant: str) -> str:
    vs = values(m)
    total = sum(vs) if variant == "sum" else sum(i * v for i, v in enumerate(vs))
    if variant == "packed":
        data = f"noncomputable def T : Nat := nat_lit {sum(v << (W * i) for i, v in enumerate(vs))}"
    else:
        data = "noncomputable def rows : List Nat := [" + ", ".join(f"nat_lit {v}" for v in vs) + "]"
        if variant == "array":
            data += "\n\nnoncomputable def arr : Array Nat := rows.toArray"
    if variant == "sum":
        expr = ("@List.rec Nat (fun _ => Nat) (nat_lit 0) (fun x _ r => Nat.add x r) rows")
    elif variant == "walk":
        expr = ("@List.rec Nat (fun _ => Nat → Nat) (fun _ => nat_lit 0)\n"
                "    (fun x _ r i => Nat.add (Nat.mul i x) (r (Nat.add i (nat_lit 1)))) rows (nat_lit 0)")
    else:
        expr = (f"@Nat.rec (fun _ => Nat) (nat_lit 0)\n"
                f"    (fun i r => Nat.add r (Nat.mul i ({LOOP[variant]}))) (nat_lit {m})")
    return f"""/-! Index benchmark, variant `{variant}`, {m} values. Generated by
`scripts/techniques/run_index_bench.py`. -/
{DEFS}
{data}

theorem check : Nat.beq ({expr}) (nat_lit {total}) = true := by
  decide +kernel
"""


def run(out: Path, ms: list[int], variants: list[str]) -> None:
    rows = load(out) if out.exists() else []
    have = done(out, "variant", "m")
    dead = {r["variant"] for r in rows if "error" in r}
    for m in ms:
        for v in variants:
            if (v, m) in have or v in dead:
                continue
            row = {"variant": v, "m": m}
            try:
                row |= measure(source(m, v))
            except RuntimeError as e:
                msg = str(e)
                row["error"] = (msg.splitlines()[0] if msg.startswith("kernel:") else
                                next((ln for ln in msg.splitlines() if "error" in ln), msg))[:300]
                dead.add(v)
            append(out, row)


COLORS = {"sum": "#6250d6", "walk": "#2a78d6", "packed": "#1baf7a", "nth_rec": "#eda100", "getD": "#e34948",
          "array": "#eb6834"}
MARKERS = {"sum": "P", "walk": "D", "packed": "^", "nth_rec": "s", "getD": "o", "array": "v"}
LABELS = {"sum": "control: List.rec sum, no position",
          "walk": "walk: List.rec with the position (ours)",
          "packed": "packed table, slot i by a shift (ours, tblGet)",
          "nth_rec": "loop over i, index in kernel form", "getD": "loop over i, List.getD",
          "array": "loop over i, Array.getD"}


def plot(out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = load(out)
    write_csv(rows, out.parent / "results.csv")
    ok = [r for r in rows if "error" not in r]
    fig, axs = plt.subplots(1, 3, figsize=(16, 5.6), dpi=150)
    panels = [("kernel_G", "Kernel instructions", "billions"),
              ("per_elem", "Per value read", "thousand instructions"),
              ("peak_GB", "Peak memory", "GB")]
    for r in ok:
        r["per_elem"] = r["kernel_G"] * 1e6 / r["m"]
    for ax, (key, title, ylabel) in zip(axs, panels):
        for v in VARIANTS:
            pts = sorted((r["m"], r[key]) for r in ok if r["variant"] == v and r[key] > 0)
            if pts:
                ax.plot(*zip(*pts), color=COLORS[v], marker=MARKERS[v], markersize=6, linewidth=2,
                        label=LABELS[v])
        style(ax, title, "values m", ylabel)
    killed = [f"{LABELS[r['variant']]}: killed at m = {r['m']:,}" for r in rows if "error" in r]
    if killed:
        axs[0].text(0.97, 0.03, "\n".join(killed), transform=axs[0].transAxes, ha="right",
                    va="bottom", fontsize=7, color="#3d3d3a")
    handles, labels = axs[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=3, frameon=False, fontsize=9)
    fig.suptitle("Walking a list against indexing into it", x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.savefig(out.parent / "index.png")


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    cmd = sys.argv[1]
    out, args = out_and_args("index", sys.argv[2:])
    if cmd == "run":
        vs = next((a.split("=")[1].split(",") for a in args if a.startswith("variants=")), VARIANTS)
        ms = [int(a) for a in args if not a.startswith("variants=")] or MS
        run(out, sorted(ms), vs)
    elif cmd == "plot":
        plot(out)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
